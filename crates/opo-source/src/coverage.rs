//! The IFC coverage table: every concrete IFC element class with its archetype, whether a class
//! template exists, its predefined types and the library objects of that class. Generated from
//! the IFC data (`elements.json` of `opo ifc`), `templates/classes.yaml` and the object sources.

use std::collections::BTreeMap;
use std::path::Path;

use serde_json::Value as Json;

use crate::{Error, catalogue, read_yaml};

/// One row of the coverage table.
#[derive(Debug, Clone, PartialEq)]
pub struct CoverageRow {
    /// The top-level group (the child of IfcElement the class descends from).
    pub group: String,
    /// Depth below IfcElement.
    pub depth: usize,
    /// IFC class.
    pub class: String,
    /// Archetype in the per-class table, if the class has an entry.
    pub archetype: Option<String>,
    /// Predefined types (without USERDEFINED / NOTDEFINED).
    pub types: Vec<String>,
    /// Library objects of this class (catalogue number or id).
    pub objects: Vec<String>,
}

/// The coverage of a library: rows in IFC tree order, and the classes in the per-class table
/// that are not concrete IFC element classes.
#[derive(Debug, Clone, Default)]
pub struct Coverage {
    /// Concrete classes, in tree order.
    pub rows: Vec<CoverageRow>,
    /// Entries of `templates/classes.yaml` that are not concrete element classes.
    pub unknown: Vec<String>,
}

/// Read the coverage of the library at `root` with the IFC data in `ifc_dir`.
pub fn coverage(root: &Path, ifc_dir: &Path) -> Result<Coverage, Error> {
    let p = ifc_dir.join("elements.json");
    let text = std::fs::read_to_string(&p).map_err(|e| Error::Io(p.clone(), e))?;
    let elements: Json =
        serde_json::from_str(&text).map_err(|e| Error::Source(format!("{}: {e}", p.display())))?;
    let classes = read_yaml(&root.join("templates/classes.yaml"))?.unwrap_or(Json::Null);
    let mut objects: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let cat = catalogue(root)?;
    for e in &cat.entries {
        if let Some(c) = e.ifc.split(" · ").next().filter(|c| !c.is_empty()) {
            objects
                .entry(c.to_owned())
                .or_default()
                .push(e.catalogue_id.clone().unwrap_or_else(|| e.id.clone()));
        }
    }
    let mut cov = Coverage::default();
    let mut group = String::new();
    let mut concrete = Vec::new();
    for e in elements.as_array().into_iter().flatten() {
        let depth = e.get(0).and_then(Json::as_u64).unwrap_or(0) as usize;
        let class = e
            .get(1)
            .and_then(Json::as_str)
            .unwrap_or_default()
            .to_owned();
        if depth == 1 {
            group = class.clone();
        }
        if e.get(2).and_then(Json::as_bool) == Some(true) {
            continue;
        }
        concrete.push(class.clone());
        cov.rows.push(CoverageRow {
            group: if depth == 0 {
                class.clone()
            } else {
                group.clone()
            },
            depth,
            archetype: classes
                .get(&class)
                .and_then(|c| c.get("archetype"))
                .and_then(Json::as_str)
                .map(str::to_owned),
            types: e
                .get(3)
                .and_then(Json::as_array)
                .into_iter()
                .flatten()
                .filter_map(|t| t.as_str().map(str::to_owned))
                .collect(),
            objects: objects.get(&class).cloned().unwrap_or_default(),
            class,
        });
    }
    cov.unknown = classes
        .as_object()
        .into_iter()
        .flatten()
        .map(|(k, _)| k.clone())
        .filter(|k| !concrete.contains(k))
        .collect();
    Ok(cov)
}

impl Coverage {
    /// The coverage table as Markdown (generated; not to be committed, decision 0016).
    pub fn to_markdown(&self) -> String {
        let with = self.rows.iter().filter(|r| r.archetype.is_some()).count();
        let types: usize = self.rows.iter().map(|r| r.types.len()).sum();
        let objs = self.rows.iter().filter(|r| !r.objects.is_empty()).count();
        let mut out = format!(
            "# IFC coverage\n\nGenerated by `opo coverage` from the IFC data, `templates/classes.yaml` and \
             `objects/*/object.yaml`; do not edit.\n\n{} concrete IFC element classes · {} with a class \
             template · {} predefined types · {} classes with at least one library object.\n",
            self.rows.len(),
            with,
            types,
            objs
        );
        let mut last = String::new();
        for r in &self.rows {
            if r.group != last {
                out += &format!(
                    "\n## {}\n\n| Class | Archetype | Template | Predefined types | Library objects |\n|---|---|---|---|---|\n",
                    r.group
                );
                last = r.group.clone();
            }
            out += &format!(
                "| {}`{}` | {} | {} | {} | {} |\n",
                "· ".repeat(r.depth.saturating_sub(1)),
                r.class,
                r.archetype.as_deref().unwrap_or("—"),
                if r.archetype.is_some() { "yes" } else { "no" },
                if r.types.is_empty() {
                    "—".to_owned()
                } else {
                    r.types.join(", ")
                },
                if r.objects.is_empty() {
                    "—".to_owned()
                } else {
                    r.objects.join(", ")
                }
            );
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_groups_and_counts() {
        let root = std::env::temp_dir().join(format!("opo-coverage-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("templates")).unwrap();
        std::fs::create_dir_all(root.join("ifc")).unwrap();
        std::fs::create_dir_all(root.join("objects/door-single-swing")).unwrap();
        std::fs::write(
            root.join("ifc/elements.json"),
            r#"[[0, "IfcElement", true, null], [1, "IfcBuiltElement", false, null], [2, "IfcDoor", false, ["DOOR", "GATE"]], [2, "IfcWall", false, ["STANDARD"]], [1, "IfcFeatureElement", true, null], [2, "IfcOpeningElement", false, ["OPENING"]]]"#,
        )
        .unwrap();
        std::fs::write(
            root.join("templates/classes.yaml"),
            "IfcDoor:\n  archetype: \"hosted\"\nIfcWall:\n  archetype: \"wall\"\nIfcNothing:\n  archetype: \"point\"\n",
        )
        .unwrap();
        std::fs::write(
            root.join("objects/door-single-swing/object.yaml"),
            "id: \"door-single-swing\"\nname: \"Door\"\ncatalogue_id: \"O-01\"\nifc:\n  class: \"IfcDoor\"\n",
        )
        .unwrap();
        let cov = coverage(&root, &root.join("ifc")).unwrap();
        std::fs::remove_dir_all(&root).unwrap();
        let classes: Vec<_> = cov.rows.iter().map(|r| r.class.as_str()).collect();
        assert_eq!(
            classes,
            ["IfcBuiltElement", "IfcDoor", "IfcWall", "IfcOpeningElement"]
        );
        assert_eq!(cov.rows[1].group, "IfcBuiltElement");
        assert_eq!(cov.rows[3].group, "IfcFeatureElement");
        assert_eq!(cov.rows[1].objects, ["O-01"]);
        assert_eq!(cov.unknown, ["IfcNothing"]);
        let md = cov.to_markdown();
        assert!(md.contains("4 concrete IFC element classes · 2 with a class template · 4 predefined types · 1 classes"));
        assert!(md.contains("| · `IfcDoor` | hosted | yes | DOOR, GATE | O-01 |"));
        assert!(md.contains("## IfcFeatureElement"));
    }
}
